-- Merge fields inside Postgres under a row lock, so concurrent edits to separate
-- properties do not overwrite one another. Invoker only, never security definer.
create or replace function public.portal_patch_record(record_id uuid, patch jsonb)
returns setof public.portal_records language sql security invoker set search_path = '' as $$
  update public.portal_records set
    payload = (payload || (patch - 'properties')) || jsonb_build_object(
      'properties', coalesce(payload->'properties','{}'::jsonb) || coalesce(patch->'properties','{}'::jsonb),
      'last_edited_time', to_jsonb(now())
    ),
    archived = coalesce((patch->>'in_trash')::boolean,(patch->>'archived')::boolean,archived),
    updated_at = now()
  where id = record_id returning *;
$$;
revoke all on function public.portal_patch_record(uuid,jsonb) from public,anon,authenticated;
grant execute on function public.portal_patch_record(uuid,jsonb) to service_role;
