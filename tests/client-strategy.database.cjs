const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { PGlite } = require(process.env.PGLITE_MODULE || "@electric-sql/pglite");
(async () => {
  const db = new PGlite();
  await db.exec("create role anon; create role authenticated; create role service_role;");
  await db.exec(fs.readFileSync(path.join(__dirname, "../migrations/20261027_client_strategies.sql"), "utf8"));
  const claim = async (client, kind = "initial", base = null) => (await db.query("select claim_client_strategy($1,$2,$3) as result", [client,kind,base])).rows[0].result;
  const finish = async (client, token, kind = "initial", base = null) => (await db.query("select finish_client_strategy($1,$2,$3) as id", [client, token, JSON.stringify({ kind, base_id: base, content: "A saved strategy", citations: [], submission_id: "123", source_hash: "hash", source_snapshot: { answers: [] }, created_by: "joe" })])).rows[0].id;
  const claims = await Promise.all([claim("a"), claim("a"), claim("a")]);
  assert.equal(claims.filter((c) => c.status === "claimed").length, 1);
  assert.equal(claims.filter((c) => c.status === "busy").length, 2);
  const initial = await finish("a", claims.find((c) => c.status === "claimed").token);
  assert.equal((await claim("a")).status, "existing");
  assert.equal((await claim("a", "revision")).status, "stale");
  await db.query("select approve_client_strategy($1,$2,$3,$4)", ["a",initial,null,"max"]);
  const alternativeClaim = await claim("a", "alternative", initial);
  const alternative = await finish("a", alternativeClaim.token, "alternative", initial);
  const revisionClaim = await claim("a", "revision", initial);
  const revision = await finish("a", revisionClaim.token, "revision", initial);
  assert.equal((await db.query("select current_id from client_strategy_state where client_id='a'")).rows[0].current_id, initial);
  await db.query("select approve_client_strategy($1,$2,$3,$4)", ["a",alternative,initial,"max"]);
  await assert.rejects(db.query("select approve_client_strategy($1,$2,$3,$4)", ["a",revision,initial,"max"]), /Current plan changed/);
  await assert.rejects(db.query("select approve_client_strategy($1,$2,$3,$4)", ["a",revision,alternative,"max"]), /older plan/);
  const clientClaim = await claim("a", "client", alternative);
  const clientVersion = await finish("a", clientClaim.token, "client", alternative);
  assert.equal((await claim("a", "client", alternative)).status, "existing");
  await assert.rejects(db.query("select approve_client_strategy($1,$2,$3,$4)", ["a",clientVersion,alternative,"max"]), /not found/);
  const first = await claim("b");
  await db.exec("update client_strategy_state set lock_until=now()-interval '1 second' where client_id='b'");
  const retry = await claim("b");
  await db.query("select release_client_strategy($1,$2)", ["b",first.token]);
  await assert.rejects(finish("b",first.token), /expired/);
  await finish("b", retry.token);
  await db.exec(fs.readFileSync(path.join(__dirname, "../migrations/20261027_strategy_evidence.sql"), "utf8"));
  const draftRevision=await claim('b','revision');
  assert.equal(draftRevision.status,'claimed');
  const refined=await finish('b',draftRevision.token,'revision');
  assert.equal((await db.query("select current_id from client_strategy_state where client_id='b'")).rows[0].current_id,null);
  await db.query('select approve_client_strategy($1,$2,$3,$4)',['b',refined,null,'max']);
  const add=async hash=>(await db.query('select add_strategy_document($1,$2,$3) as id',['b',JSON.stringify({filename:'deck.pdf',content_base64:'JVBERi0=',byte_size:5,sha256:hash,period:'2026'}),'max'])).rows[0].id;
  assert.equal(await add('one'),await add('one'));
  await Promise.all([add('two'),add('three')]);
  await assert.rejects(add('four'),/Three supporting/);
  await db.exec("set role authenticated");
  await assert.rejects(db.query('select * from client_strategy_documents'),/permission denied/);
  await assert.rejects(add('five'),/permission denied/);
  await assert.rejects(db.query("select * from client_strategy_versions"), /permission denied/);
  await assert.rejects(claim("c"), /permission denied/);
  await db.close();
  console.log("PASS: atomic claims, shared initial, approved pointer, alternatives, stale approval, client-draft reuse, expired workers, private storage permissions.");
})().catch((error) => { console.error(error); process.exit(1); });
